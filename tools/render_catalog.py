#!/usr/bin/env python3
"""Render skills/CATALOG.md from SKILL.md frontmatter."""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKILLS = ROOT / "skills"
OUT = ROOT / "skills" / "CATALOG.md"


def parse_frontmatter(text: str) -> dict[str, str]:
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end < 0:
        return {}
    block = text[3:end].strip()
    data: dict[str, str] = {}
    for line in block.splitlines():
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        data[key.strip()] = value.strip().strip("\"'")
    return data


def main() -> int:
    rows: list[tuple[str, str, str]] = []
    for skill_dir in sorted(SKILLS.iterdir()):
        skill_md = skill_dir / "SKILL.md"
        if not skill_md.exists():
            continue
        meta = parse_frontmatter(skill_md.read_text(encoding="utf-8"))
        name = meta.get("name") or skill_dir.name
        desc = meta.get("description") or ""
        version = meta.get("version") or ""
        rows.append((name, version, desc))

    lines = [
        "# Skills catalog",
        "",
        "Generated by `tools/render_catalog.py`.",
        "",
        "| Skill | Version | Description |",
        "|-------|---------|-------------|",
    ]
    for name, version, desc in rows:
        safe_desc = desc.replace("|", "\\|")
        lines.append(f"| `{name}` | {version or '-'} | {safe_desc} |")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} skills)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
